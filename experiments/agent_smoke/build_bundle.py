def build(artifacts, output_dir):
    artifacts, output_dir = Path(artifacts).resolve(), Path(output_dir).resolve()
    files = {}
    for folder in ("llm_adapter", "sim", "eval"):
        for path in sorted((ROOT / folder).rglob("*")):
            if (
                path.is_file()
                and path.suffix in {".py", ".txt", ".md"}
                and "__pycache__" not in path.parts
            ):
                files[path.relative_to(ROOT).as_posix()] = path
    for name in (
        "twin_v2_config.json",
        "failure_model.json",
        "cases_certify_v2.json",
        "dubai_hourly_2015_2025_era5.csv",
    ):
        files["experiments/input_rebuild/artifacts/inputs/" + name] = artifacts / "inputs" / name
    for name in ("source_manifest.json", "weather_metadata.json", "validation.json"):
        files["experiments/input_rebuild/artifacts/" + name] = artifacts / name
    missing = [str(path) for path in files.values() if not path.is_file()]
    if missing:
        raise FileNotFoundError("Missing package inputs: " + ", ".join(missing))
    manifest = {
        "format_version": 1,
        "scope": "Private development package; includes Bosch-derived configuration.",
        "files_sha256": {
            name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in files.items()
        },
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    bundle = output_dir / "smartbai_agent_smoke_bundle.zip"
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, path in files.items():
            archive.write(path, "project/" + name)
        archive.writestr("project/agent_smoke_bundle_manifest.json", json.dumps(manifest, indent=2))
    cells = [{"cell_type": "markdown", "metadata": {}, "source": INTRO.splitlines(keepends=True)}]
    for source in (LOAD, INSTALL, CONFIGURE, PLUMBING, EVALUATE, PACKAGE):
        cells.append(
            {
                "cell_type": "code",
                "metadata": {},
                "execution_count": None,
                "outputs": [],
                "source": source.splitlines(keepends=True),
            }
        )
    notebook = {
        "nbformat": 4,
        "nbformat_minor": 4,
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
    }
    path = output_dir / "kaggle_qwen35_agent_smoke.ipynb"
    path.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
    return path, bundle


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--artifacts", type=Path, default=ROOT / "experiments/input_rebuild/artifacts"
    )
    parser.add_argument("--output-dir", type=Path, default=HERE)
    args = parser.parse_args()
    for path in build(args.artifacts, args.output_dir):
        print(path)


if __name__ == "__main__":
    main()
